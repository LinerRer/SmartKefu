"""查询归一化：把用户口语/缩写展开成文档里的规范用词，再进检索。

为什么需要：向量与 BM25 都吃"字面/语义接近"，用户说"计网"而文档写"计算机网络"，
rerank 打分会很低（实测 0.008 判未命中），展开成"计算机网络"后命中（0.932）。

为什么用替换而非追加：实测"计网 计算机网络 是什么"这种追加式反而把 rerank 分数
拉到 0.104（多词干扰精排），纯替换效果最好。别名表保守收录高置信缩写，避免误伤。

设计取舍：这是一层确定性的词典映射，不额外调用 LLM（省钱、可控、可单测）；
生产可升级为"词典 + 小模型改写"双路，词典命中优先。
"""
import re

# 规范词 ← 别名（用户可能输入的缩写/口语/同义词）。命中任一别名即替换为规范词。
# 长别名放前面，避免"网"这类短词抢先误伤，故按长度降序匹配。
ALIAS_MAP: dict[str, list[str]] = {
    "计算机网络": ["计网", "计算机网络技术", "网络基础"],
    "操作系统": ["操作系统原理", "OS原理", "os原理"],
    "数据结构": ["数构", "数据结构与算法"],
    "数据库": ["DB", "db系统", "数据库系统"],
    "退货政策": ["退换货政策", "退货规定", "退款政策", "怎么退货", "如何退货"],
    "续航": ["电池续航", "能用多久", "待机时间", "电量"],
    "降噪": ["主动降噪", "噪音消除", "隔音"],
    "保修": ["质保", "三包", "保修期"],
    "物流": ["快递", "发货", "配送"],
    "价格": ["多少钱", "售价", "报价"],
}

# 预编译：按别名长度降序，长词优先替换（"计算机网络技术" 不被 "网络" 抢先）
_RULES: list[tuple[re.Pattern, str]] = []
for _norm, _aliases in ALIAS_MAP.items():
    for _alias in sorted(_aliases, key=len, reverse=True):
        # 中文无词边界，直接子串匹配；英文缩写用不区分大小写
        _RULES.append((re.compile(re.escape(_alias), re.IGNORECASE), _norm))


def normalize_query(query: str) -> str:
    """把查询里的别名替换为规范词。无命中则原样返回。"""
    if not query:
        return query
    out = query
    for pattern, norm in _RULES:
        out = pattern.sub(norm, out)
    return out
